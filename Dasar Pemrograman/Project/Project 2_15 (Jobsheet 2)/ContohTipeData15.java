public class ContohTipeData15 {
    public static void main(String[] args) {
    
        char golongan_darah = 'O';
        short jarak = 130;
        short jumlah_penduduk = 1025;
        float suhu = 36.5F;
        double berat = 0.5467812345;
        long saldo = 150000000;
        int angka_desimal = 0x10;

        System.out.println("Golongan darah saya: " +  golongan_darah);
        System.out.println("Jarak: " + jarak);
        System.out.println("Jumlah penduduk: " + jumlah_penduduk);
        System.out.println("Suhu: " + suhu);
        System.out.println("Berat: " + (float) berat);
        System.out.println("Saldo: " + saldo);
        System.out.println("Angka desimal: " + angka_desimal);
    }
    
}